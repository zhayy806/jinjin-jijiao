"""食材别名归一：菜谱库里同一食材常有不同叫法（番茄/西红柿、米/米饭/大米…），
做菜匹配和展示前先归一到规范名，避免「选了食材却匹配不到菜」。

只用于匹配与展示，不改 portion.FOODS 里的热量/价格数据。
"""

# 别名 → 规范名。规范名尽量取 portion.FOODS 里已有的名字，方便展示。
CANON = {
    # 番茄 / 西红柿
    "番茄": "西红柿",
    # 大米 / 米 / 米饭
    "米": "大米",
    "米饭": "大米",
    # 鸡胸肉 / 鸡腿 / 鸡肉 / 鸡
    "鸡": "鸡肉",
    "鸡胸肉": "鸡肉",
    "鸡腿": "鸡肉",
    # 虾 / 虾仁
    "虾仁": "虾",
    # 葱 / 大葱
    "葱": "大葱",
    # 胡萝卜 / 葫芦卜（爬虫数据里的错别字）
    "葫芦卜": "胡萝卜",
    # 面粉 / 方面（错别字）
    "方面": "面粉",
    # 菌菇 / 海鲜菇
    "海鲜菇": "菌菇",
    # 糖
    "糖": "白糖",
    "砂糖": "白糖",
    "细砂糖": "白糖",
}


def canonical(food: str) -> str:
    """返回规范名；没有映射的食材原样返回。"""
    return CANON.get(food, food)
