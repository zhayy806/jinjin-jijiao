def seed_recipes() -> int:
    """若菜谱表为空，灌入种子菜谱，返回灌入数量。"""
    with SessionLocal() as db:
        if db.query(Recipe).count() > 0:
            return 0
        for r in SEED_RECIPES:
            recipe = Recipe(name=r["name"], category=r["category"], steps=r["steps"])
            db.add(recipe)
            db.flush()
            for food, qty, unit in r["ingredients"]:
                db.add(Ingredient(recipe_id=recipe.id, food=food, quantity=qty, unit=unit))
        db.commit()
    return len(SEED_RECIPES)


def sync_seed_steps() -> int:
    """把种子菜谱的最新做法同步到已有数据（按菜名匹配，幂等）。

    旧版本灌入的种子菜谱做法较简略，这里用最新版覆盖，
    让已经部署的库也能显示完整做法教程。
    """
    updated = 0
    with SessionLocal() as db:
        for r in SEED_RECIPES:
            row = db.query(Recipe).filter(Recipe.name == r["name"]).first()
            if row and row.steps != r["steps"]:
                row.steps = r["steps"]
                updated += 1
        db.commit()
    return updated
